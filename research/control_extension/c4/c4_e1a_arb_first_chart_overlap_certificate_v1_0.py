"""C4-E1a: Arb certificate for the first positive-volume chart overlap.

The chart centres and frames are frozen binary64 data generated by the C4-E0
mixed trajectory.  All membership, projective-denominator, Jacobian, Neumann,
response, gradient, and local-residence bounds on the declared 14D overlap
box are evaluated with 256-bit outward-rounded Arb/Acb arithmetic.

This certifies a positive-volume overlap subbox and a positive local residence
window in each adjacent chart.  It does not certify that a nonzero flowpipe is
transported into that subbox, and therefore is not yet a continuation theorem.
"""

